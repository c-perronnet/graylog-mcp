// BLUE-04 — setup_pipeline_for_stream.
//
// Variable-length chain that builds a complete pipeline-for-a-stream from
// structured-intent transforms:
//   step 1..N: createRule (one per transform; DSL compiled via emitRule)
//   step N+1: createPipeline (single-stage referencing all N rule titles in
//             order; source string is plain text — no apply-time substitution
//             needed because rule titles are locked at build() time)
//   step N+2: connectToStream (wires the new pipeline to args.streamId;
//             SERVER_ASSIGNED_SENTINEL+"step{N+1}" placeholder inside
//             pipeline_ids[0] is replaced by executeChain at apply-time with
//             the real pipeline id from step N+1's response)
//
// N is bounded by the schema (1..20) so the chain never grows unbounded
// (T-06-04-04 DoS mitigation). For >20 transforms the agent partitions across
// multiple blueprint invocations — partial-failure transcripts make
// per-batch progress visible.
//
// Composition contract (D-09): Imports services from src/services/pipelines.js
// + DSL emitter from src/pipeline-dsl/emit.js — NEVER from src/tools/<domain>/.
// Pinned by Task 3 grep test.
//
// emitRule reuse (Phase 4 inheritance): every transform's RuleSpec compiles
// through the same emitter as create_pipeline_rule. All literals route
// through escape.js (T-06-04-01 mitigation — no agent-controlled string
// reaches the DSL output unescaped).

import { defineMutatingHandler } from "../_shared/handler.js";
import { SetupPipelineForStreamSchema } from "./schemas.js";
import {
    createPipeline,
    createRule,
    connectToStream,
} from "../../services/pipelines.js";  // D-09 boundary — services only
import { executeChain } from "../_shared/blueprint-chain.js";
import { emitRule } from "../../pipeline-dsl/emit.js";
import { escapeString } from "../../pipeline-dsl/escape.js";
import { SERVER_ASSIGNED_SENTINEL } from "../_shared/dry-run.js";

// Architectural-boundary markers — see setup-debug-log-dropping.js header
// for the rationale on why we import service functions but call through
// executeChain instead. D-09 grep audit checks the import path, not runtime
// invocation.
void createPipeline;
void createRule;
void connectToStream;

export const handleSetupPipelineForStream = defineMutatingHandler({
    name: "setup_pipeline_for_stream",
    schema: SetupPipelineForStreamSchema,
    async build(args) {
        // Steps 1..N — one createRule per transform. emitRule compiles
        // each RuleSpec to a DSL source string (Phase 4 inheritance).
        const ruleSteps = args.transforms.map((spec, i) => {
            const source = emitRule(spec);
            return {
                step: i + 1,
                tool: "create_pipeline_rule",
                request: {
                    method: "POST",
                    path: "/api/system/pipelines/rule",
                    body: {
                        title: spec.name,
                        description: `Generated by setup_pipeline_for_stream (transform ${i + 1}/${args.transforms.length})`,
                        source,
                    },
                },
                postApplyEstimate: { id: SERVER_ASSIGNED_SENTINEL },
            };
        });

        const N = args.transforms.length;

        // Step N+1: createPipeline. Source aggregates all rule titles into
        // a single stage; titles travel verbatim in the source string (no
        // apply-time placeholder needed because rule titles are stable
        // across the build → apply boundary). escapeString defends each
        // title-bearing literal against embedded-quote injection
        // (T-06-04-03 mitigation).
        const stageLines = args.transforms.map(
            (t) => `    rule "${escapeString(t.name)}"`,
        );
        const pipelineSource = [
            `pipeline "${escapeString(args.pipelineTitle)}"`,
            `stage 0 match either`,
            ...stageLines,
            `end`,
        ].join("\n");
        const pipelineStep = {
            step: N + 1,
            tool: "create_pipeline",
            request: {
                method: "POST",
                path: "/api/system/pipelines/pipeline",
                body: {
                    title: args.pipelineTitle,
                    description: args.pipelineDescription ?? `Generated pipeline with ${N} transform(s) for stream ${args.streamId}`,
                    source: pipelineSource,
                },
            },
            // No dependsOn — rules referenced by TITLE in the source string;
            // executeChain's sequential walk guarantees ordering.
            postApplyEstimate: { id: SERVER_ASSIGNED_SENTINEL },
        };

        // Step N+2: connectToStream — depends on step N+1's pipeline id.
        const connectStep = {
            step: N + 2,
            tool: "connect_pipelines_to_stream",
            request: {
                method: "POST",
                path: "/api/system/pipelines/connections/to_stream",
                body: {
                    stream_id: args.streamId,
                    pipeline_ids: [`${SERVER_ASSIGNED_SENTINEL}step${N + 1}`],
                },
            },
            dependsOn: { from: `step${N + 1}.response.id`, as: "pipeline_ids[0]" },
        };

        const chain = [...ruleSteps, pipelineStep, connectStep];

        return {
            chain,
            // Primary preview mirrors the FINAL step — the agent's mental
            // model is "wire this pipeline to my stream".
            method: "POST",
            path: "/api/system/pipelines/connections/to_stream",
            body: connectStep.request.body,
            postApplyEstimate: { id: args.streamId },
        };
    },
    async apply(client, req) {
        const result = await executeChain(client, req.chain);
        if (result.isError) return result;
        return result.transcript[result.transcript.length - 1].response;
    },
    summarize: (args) =>
        `Set up pipeline "${args.pipelineTitle}" for stream ${args.streamId} with ${args.transforms.length} transform(s) (${args.transforms.length + 2}-step chain)`,
});
